#!/usr/bin/env python3
"""Writes the help book's Menus and Keyboard Shortcuts pages (FR-14.6) from Colorbee's own menus.

Usage: help-pages.py menus.json help-folder. The JSON comes from `Colorbee -ColorbeeDumpMenus path` (HelpDump.swift),
so a renamed command or a changed default can't leave the help wrong. Run through `make help`.
"""
import html
import json
import sys
from pathlib import Path

dump = json.loads(Path(sys.argv[1]).read_text())
folder = Path(sys.argv[2])

# Menus macOS fills in itself have no tooltip of Colorbee's.
EXTRA = {"Services": "Other apps' services, provided by macOS."}


def page(name, title, description, keywords, body):
    (folder / name).write_text(f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{title}</title>
    <meta name="AppleTitle" content="{title}">
    <meta name="description" content="{description}">
    <meta name="keywords" content="{keywords}">
    <link rel="stylesheet" href="../shared/help.css">
    <!-- Generated by `make help` from Colorbee's menus. Don't edit by hand. -->
</head>
<body>
    <nav class="back"><a href="index.html">Colorbee Help</a></nav>
{body}</body>
</html>
""")


def anchor(text):
    return "".join(c if c.isalnum() else "-" for c in text.lower()).strip("-")


def grouped(entries):
    groups = {}
    for entry in entries:
        groups.setdefault(entry["menu"], []).append(entry)
    return groups


def key(entry):
    return html.escape(entry.get("shortcut") or "")


def folded(entries):
    """Submenu items that share a description and have no shortcuts, as one row: "Rotate ▸ 90° Clockwise, 180°"."""
    rows = []
    for entry in entries:
        parent, _, leaf = entry["title"].rpartition(" ▸ ")
        last = rows[-1] if rows else None
        if (parent and last and last.get("parent") == parent and last["summary"] == entry.get("summary")
                and not entry.get("shortcut") and not last.get("shortcut")):
            last["leaves"].append(leaf)
        else:
            rows.append({**entry, "parent": parent, "leaves": [leaf] if parent else [], "summary": entry.get("summary")})
    for row in rows:
        if len(row["leaves"]) > 1:
            row["title"] = f"{row['parent']} ▸ " + ", ".join(row["leaves"])
    return rows


# Menu items macOS adds after Colorbee has launched, so the dump (made before then) doesn't have them: each goes after
# the item named (review P, finding 8).
ADDED_BY_MACOS = [("File", "Open…", {"menu": "File", "title": "Open Recent",
                                     "summary": "Open an image or project you opened recently. Clear Menu forgets the list."})]
for menu, after, entry in ADDED_BY_MACOS:
    items = dump["menus"]
    index = next((i for i, e in enumerate(items) if e["menu"] == menu and e["title"] == after), None)
    if index is not None and not any(e["menu"] == menu and e["title"] == entry["title"] for e in items):
        items.insert(index + 1, entry)

menus = {menu: folded(entries) for menu, entries in grouped(dump["menus"]).items()}

body = ['    <a name="menus"></a>\n    <h1>Menus</h1>\n',
        '    <p class="lead">Every command in Colorbee\'s menus, with its shortcut and what it does.</p>\n',
        '    <p>Shortcuts shown are the defaults. You can change them in Colorbee ▸ Settings ▸ Shortcuts.</p>\n',
        "    <p>" + " · ".join(f'<a href="#{anchor(m)}">{html.escape(m)}</a>' for m in menus) + "</p>\n"]
for menu, entries in menus.items():
    body.append(f'\n    <a name="{anchor(menu)}"></a>\n    <h2>{html.escape(menu)}</h2>\n    <table>\n')
    body.append("        <tr><th>Command</th><th>Shortcut</th><th>What it does</th></tr>\n")
    for entry in entries:
        summary = entry.get("summary") or EXTRA.get(entry["title"], "")
        body.append(f"        <tr><td>{html.escape(entry['title'])}</td><td>{key(entry)}</td>"
                    f"<td>{html.escape(summary)}</td></tr>\n")
    body.append("    </table>\n")
page("menus.html", "Menus",
     "Every command in Colorbee's menus, with its default keyboard shortcut and a line on what it does.",
     "menu, menus, command, commands, File, Edit, View, Image, Layer, Page, Adjustments, Effects, Redact, Window",
     "".join(body))

body = ['    <a name="shortcuts"></a>\n    <h1>Keyboard shortcuts</h1>\n',
        '    <p class="lead">Every shortcut in Colorbee, as it comes. You can change any of them in '
        'Colorbee ▸ Settings ▸ Shortcuts, except the Mac\'s own, such as Quit and Hide.</p>\n',
        '\n    <a name="tools"></a>\n    <h2>Tools and canvas keys</h2>\n',
        "    <p>Single keys work whenever you're not typing text.</p>\n    <table>\n",
        "        <tr><th>Key</th><th>Tool or action</th></tr>\n"]
for entry in dump["canvasKeys"]:
    body.append(f"        <tr><td>{key(entry)}</td><td>{html.escape(entry['title'])}</td></tr>\n")
body.append("        <tr><td>Space (hold)</td><td>Move around the image</td></tr>\n")
body.append("        <tr><td>Shift (while dragging)</td><td>Keep lines and strokes straight, and shapes in proportion</td></tr>\n")
body.append("    </table>\n")
for menu, entries in menus.items():
    with_keys = [e for e in entries if e.get("shortcut")]
    if not with_keys:
        continue
    body.append(f'\n    <a name="{anchor(menu)}"></a>\n    <h2>{html.escape(menu)} menu</h2>\n    <table>\n')
    body.append("        <tr><th>Shortcut</th><th>Command</th></tr>\n")
    for entry in with_keys:
        body.append(f"        <tr><td>{key(entry)}</td><td>{html.escape(entry['title'])}</td></tr>\n")
    body.append("    </table>\n")
body.append('\n    <p>See <a href="menus.html">Menus</a> for what each command does.</p>\n')
page("keyboard-shortcuts.html", "Keyboard shortcuts",
     "Every default keyboard shortcut in Colorbee: the single-key tools and the menu commands.",
     "keyboard, shortcut, shortcuts, keys, hotkey, single key, tool keys, command",
     "".join(body))
